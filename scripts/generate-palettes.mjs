import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const library = process.argv[2]
	? pathToFileURL(resolve(process.argv[2])).href
	: '@material/material-color-utilities';
const {
	argbFromHex, hexFromArgb, Hct,
	SchemeTonalSpot, SchemeVibrant, SchemeExpressive, SchemeNeutral, SchemeMonochrome
} = await import(library);

const seeds = {
	red: '#C43747', yellow: '#EAB318', blue: '#296EDC', green: '#278953', purple: '#7951CE'
};
const graySeed = '#777777';
const styles = {
	'tonal-spot': SchemeTonalSpot, vibrant: SchemeVibrant, expressive: SchemeExpressive, neutral: SchemeNeutral
};
const grayContrast = { monochrome: 0, medium: 0.5, high: 1 };
const roles = [
	'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
	'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
	'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
	'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
	'surfaceContainerLow', 'surfaceContainer', 'surfaceContainerHigh', 'outline', 'outlineVariant',
	'error', 'onError', 'errorContainer', 'onErrorContainer'
];

function rule(selector, scheme) {
	const declarations = roles.map(role => {
		const name = role.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`);
		return `\t--${name}: ${hexFromArgb(scheme[role])};`;
	});
	for (const role of ['primary', 'error']) {
		const color = scheme[role];
		const rgb = [(color >>> 16) & 255, (color >>> 8) & 255, color & 255];
		declarations.push(`\t--${role}-rgb: ${rgb.join(', ')};`);
	}
	return `${selector} {\n${declarations.join('\n')}\n}`;
}

const css = ['/* Generated by scripts/generate-palettes.mjs with Material Color Utilities 0.4.0. */\n@layer m3e-palettes {'];

for (const [family, seed] of Object.entries({ ...seeds, gray: graySeed }))
	css.push(`.m3e-family-swatch[data-family="${family}"] { --m3e-family-seed: ${seed}; }`);

function addPalette(name, createScheme) {
	const selector = `[data-m3e-palette="${name}"]`;
	const dark = ':root[data-darkmode="true"]';
	css.push(rule(selector, createScheme(false)));
	css.push(rule(`${dark}${selector},\n${dark} ${selector}`, createScheme(true)));
}

for (const [family, seed] of Object.entries(seeds)) {
	const source = Hct.fromInt(argbFromHex(seed));
	for (const [style, Scheme] of Object.entries(styles))
		addPalette(`${family}-${style}`, dark => new Scheme(source, dark, 0, '2025'));
}

const gray = Hct.fromInt(argbFromHex(graySeed));
for (const [style, contrast] of Object.entries(grayContrast))
	addPalette(`gray-${style}`, dark => new SchemeMonochrome(gray, dark, contrast));

writeFileSync(new URL('../htdocs/luci-static/m3e/palettes.css', import.meta.url), `${css.join('\n\n')}\n}\n`);
